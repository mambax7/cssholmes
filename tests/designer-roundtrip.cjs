/* Run through designer-http.php --browser; uses real endpoints in its isolated test site. */
const assert = require('node:assert/strict');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
(async () => {
    const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe' });
    try {
        const context = await browser.newContext({ extraHTTPHeaders: { 'X-Test-Role': 'writer' } });
        const page = await context.newPage();
        const errors = [];
        page.on('pageerror', error => errors.push(error.message));
        await page.goto(process.argv[2] + '/canvas.php');
        await page.waitForFunction(() => !!window.CssHolmesDesigner);
        const boot = await page.locator('#cssholmes-designer-config').textContent();
        assert.equal(JSON.parse(boot).token, '', 'Page source must not embed a session token');
        assert.ok(JSON.parse(boot).properties['font-size']);
        await page.getByRole('button', { name: 'Open theme designer', exact: true }).click();
        const panel = page.locator('#cssholmes-designer');
        await panel.getByRole('button', { name: 'Pick element', exact: true }).click();
        await page.getByRole('heading', { name: 'A thoughtful response' }).click();
        await panel.getByLabel('Font size', { exact: true }).fill('31px');
        await panel.getByLabel('Text color', { exact: true }).fill('#b51234');
        await panel.getByLabel('Set name', { exact: true }).fill('Browser set');
        await panel.getByRole('button', { name: 'Save as new set', exact: true }).click();
        await page.waitForFunction(() => document.querySelector('#cssholmes-designer').shadowRoot.querySelector('[data-status]').textContent === 'Set saved in library. Theme unchanged.');
        const beforePublication = await browser.newPage();
        await beforePublication.goto(process.argv[2] + '/canvas.php');
        assert.equal(await beforePublication.locator('h4').first().evaluate(el => getComputedStyle(el).fontSize), '18px', 'Save as must not publish');
        await beforePublication.close();
        await panel.getByRole('button', { name: 'Save to theme', exact: true }).click();
        await page.waitForFunction(() => document.querySelector('#cssholmes-designer').shadowRoot.querySelector('[data-status]').textContent === 'Saved to theme.');
        await panel.getByRole('button', { name: 'Close', exact: true }).click();
        await page.waitForFunction(() => getComputedStyle(document.querySelector('h4')).fontSize === '31px');
        await page.reload();
        assert.equal(await page.locator('h4').first().evaluate(el => getComputedStyle(el).fontSize), '31px');
        const visitor = await browser.newPage();
        await visitor.goto(process.argv[2] + '/canvas.php');
        assert.equal(await visitor.locator('#cssholmes-designer-config').count(), 0);
        assert.equal(await visitor.locator('#cssholmes-designer').count(), 0);
        assert.equal(await visitor.locator('h4').last().evaluate(el => getComputedStyle(el).color), 'rgb(181, 18, 52)');
        await page.evaluate(() => window.CssHolmesDesigner.select(document.querySelector('h4')));
        await panel.getByRole('button', { name: 'Reset selected', exact: true }).click();
        await panel.getByRole('button', { name: 'Save to theme', exact: true }).click();
        await page.waitForFunction(() => document.querySelector('#cssholmes-designer').shadowRoot.querySelector('[data-status]').textContent === 'Saved to theme.');
        await visitor.reload();
        assert.equal(await visitor.locator('h4').first().evaluate(el => getComputedStyle(el).fontSize), '18px');
        assert.equal(await visitor.locator('#cssholmes-theme-style').count(), 0);
        const list = await (await context.request.get(process.argv[2] + '/modules/cssholmes/sets.php?theme=demo')).json();
        const savedSet = list.library.sets.find(set => set.name === 'Browser set');
        assert.ok(savedSet);
        await panel.getByLabel('Style sets', { exact: true }).selectOption(savedSet.id);
        await panel.getByRole('button', { name: 'Preview selected', exact: true }).click();
        await page.waitForFunction(() => getComputedStyle(document.querySelector('h4')).fontSize === '31px');
        await panel.locator('[data-library-transfer] summary').click();
        const download = page.waitForEvent('download');
        await panel.getByRole('button', { name: 'Export portable set', exact: true }).click();
        const stream = await (await download).createReadStream(), chunks = [];
        for await (const chunk of stream) chunks.push(chunk);
        const exported = JSON.parse(Buffer.concat(chunks).toString('utf8'));
        assert.equal(exported.format, 'xoops-theme-set');
        assert.ok(exported.styles.some(style => style.target === 'comment.title'));
        await panel.getByLabel('Import set JSON', { exact: true }).setInputFiles({ name: 'roundtrip.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(exported)) });
        page.once('dialog', dialog => dialog.accept());
        await panel.getByRole('button', { name: 'Preview import', exact: true }).click();
        await panel.getByRole('button', { name: 'Save imported set', exact: true }).waitFor({ state: 'visible' });
        await panel.getByRole('button', { name: 'Save imported set', exact: true }).click();
        await page.waitForFunction(() => document.querySelector('#cssholmes-designer').shadowRoot.querySelector('[data-status]').textContent === 'Set saved in library. Theme unchanged.');
        await panel.getByLabel('Style sets', { exact: true }).selectOption('palette-ocean');
        const paletteSelect = panel.getByLabel('Style sets', { exact: true });
        assert.equal(await paletteSelect.locator('option[value="palette-ocean"] .palette-option-swatches span').count(), 4);
        if (await page.evaluate(() => CSS.supports('appearance', 'base-select'))) {
            await paletteSelect.click();
            await paletteSelect.getByRole('option', { name: 'Forest', exact: true }).click();
            assert.equal(await paletteSelect.inputValue(), 'palette-forest');
            const nextChoice = await paletteSelect.evaluate(select => select.options[select.selectedIndex + 1].value);
            await paletteSelect.click();
            await page.keyboard.press('ArrowDown');
            await page.keyboard.press('Enter');
            assert.equal(await paletteSelect.inputValue(), nextChoice, 'Swatch choices retain native arrow-key navigation');
            await paletteSelect.selectOption('palette-ocean');
            if (process.env.DESIGNER_PALETTE_SCREENSHOT) {
                await page.setViewportSize({ width: 1280, height: 1000 });
                await paletteSelect.click();
                await page.screenshot({ path: process.env.DESIGNER_PALETTE_SCREENSHOT });
                await page.keyboard.press('Escape');
            }
        }
        page.once('dialog', dialog => dialog.accept());
        await panel.getByRole('button', { name: 'Preview selected', exact: true }).click();
        await page.waitForFunction(() => getComputedStyle(document.body).backgroundColor === 'rgb(240, 249, 255)');
        await panel.locator('[data-library-original] summary').click();
        page.once('dialog', dialog => dialog.accept());
        await panel.getByRole('button', { name: 'Reset theme to original', exact: true }).click();
        await page.waitForFunction(() => document.querySelector('#cssholmes-designer').shadowRoot.querySelector('[data-status]').textContent === 'Theme reset to original. Library sets kept.');
        assert.equal(await page.locator('h4').first().evaluate(el => getComputedStyle(el).fontSize), '18px');
        const retained = await (await context.request.get(process.argv[2] + '/modules/cssholmes/sets.php?theme=demo')).json();
        assert.ok(retained.library.sets.filter(set => set.name === 'Browser set').length >= 2, 'Original reset must retain both saved and imported sets');
        const adminPage = await context.newPage();
        adminPage.on('pageerror', error => errors.push(error.message));
        await adminPage.goto(process.argv[2] + '/library.php');
        const library = adminPage.locator('#cssholmes-theme-sets');
        const browserRow = library.getByRole('rowheader', { name: 'Browser set', exact: true }).first().locator('..');
        await browserRow.waitFor();
        assert.equal(await library.locator('tbody').count(), 2, 'Admin groups every installed theme');
        await browserRow.getByRole('button', { name: 'Like', exact: true }).click();
        await library.getByRole('status').filter({ hasText: 'Like updated.' }).waitFor();
        await browserRow.getByRole('button', { name: 'Unlike', exact: true }).waitFor();
        adminPage.once('dialog', dialog => dialog.accept());
        await browserRow.getByRole('button', { name: 'Activate', exact: true }).click();
        await library.getByRole('status').filter({ hasText: 'Set activated.' }).waitFor();
        await visitor.reload();
        assert.equal(await visitor.locator('h4').first().evaluate(el => getComputedStyle(el).fontSize), '31px');
        adminPage.once('dialog', dialog => dialog.accept());
        await library.getByRole('button', { name: 'Reset to original', exact: true }).first().click();
        await library.getByRole('status').filter({ hasText: 'Original theme styles restored. Named sets are kept.' }).waitFor();
        await visitor.reload();
        assert.equal(await visitor.locator('h4').first().evaluate(el => getComputedStyle(el).fontSize), '18px');
        await page.reload();
        await page.waitForFunction(() => !!window.CssHolmesDesigner);
        await page.evaluate(() => window.CssHolmesDesigner.select(document.querySelector('.fixture-parent strong')));
        assert.equal(await panel.getByLabel('Selector', { exact: true }).inputValue(), 'section.fixture-parent > span > strong');
        await panel.getByLabel('Font size', { exact: true }).fill('23px');
        await panel.getByRole('button', { name: 'Save to theme', exact: true }).click();
        await page.waitForFunction(() => document.querySelector('#cssholmes-designer').shadowRoot.querySelector('[data-status]').textContent === 'Saved to theme.');
        await visitor.reload();
        assert.equal(await visitor.locator('.fixture-parent strong').evaluate(el => getComputedStyle(el).fontSize), '23px', 'Generic nested elements must persist selector-derived labels');
        await panel.getByLabel('Set name', { exact: true }).fill('Nested selector set');
        await panel.getByRole('button', { name: 'Save as new set', exact: true }).click();
        await page.waitForFunction(() => document.querySelector('#cssholmes-designer').shadowRoot.querySelector('[data-status]').textContent === 'Set saved in library. Theme unchanged.');
        assert.deepEqual(errors, []);
        console.log('Designer roundtrip: preload, named save without publishing, live save/reload, portable export/import, palette preview and original reset passed.');
    } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
