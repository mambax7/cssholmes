'use strict';
// Real rendered specimens and production endpoints, temporary storage only.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const playwright = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const engine = process.env.XSTYLES_BROWSER || 'chromium';
assert.ok(['chromium', 'firefox'].includes(engine));
(async () => {
    const browser = await playwright[engine].launch({ headless: true, ...(engine === 'chromium' && process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : {}) });
    try {
        for (const theme of ['xbootstrap5', 'mytheme6']) {
            const context = await browser.newContext({ viewport: { width: 1280, height: 960 }, extraHTTPHeaders: { 'X-Test-Role': 'writer' } });
            const page = await context.newPage(), errors = [];
            page.on('pageerror', error => errors.push(error.message));
            page.on('dialog', dialog => dialog.accept());
            const url = `${process.argv[2]}/${theme}.php`;
            await page.goto(url);
            assert.equal(await page.locator('.xs-example').count(), 3);
            const heading = page.locator('#xs-theme-cards_card-title');
            const original = await heading.evaluate(el => getComputedStyle(el).fontSize);
            assert.notEqual(original, '31px');
            const panel = page.locator('#cssholmes-designer');
            const status = text => page.waitForFunction(text => document.querySelector('#cssholmes-designer').shadowRoot.querySelector('[data-status]').textContent === text, text);
            const frames = async () => {
                await page.locator('[data-xs-responsive] > summary').click();
                await page.selectOption('[data-xs-width]', 'all');
                await page.waitForFunction(() => document.querySelectorAll('[data-xs-frames] iframe').length === 3 && [...document.querySelectorAll('[data-xs-frames] iframe')].every(f => f.contentDocument?.querySelector('#xs-theme-cards_card-title')));
                assert.deepEqual(await page.locator('[data-xs-frames] iframe').evaluateAll(nodes => nodes.map(f => f.contentWindow.innerWidth)), [360, 768, 1280]);
            };
            const frameSizes = () => page.locator('[data-xs-frames] iframe').evaluateAll(nodes => nodes.map(f => f.contentWindow.getComputedStyle(f.contentDocument.querySelector('#xs-theme-cards_card-title')).fontSize));
            await frames();
            const before = await frameSizes();
            await page.getByRole('button', { name: 'Open theme designer', exact: true }).click();
            await panel.getByRole('button', { name: 'Pick element', exact: true }).click();
            await heading.click();
            await panel.getByLabel('Font size', { exact: true }).fill('31px');
            await panel.getByLabel('Text color', { exact: true }).fill('#222222');
            await panel.locator('[data-diagnostics] > summary').click();
            await page.waitForFunction(() => document.querySelector('#cssholmes-designer').shadowRoot.querySelector('[data-contrast]').textContent.length > 0);
            await panel.locator('[data-token-list] dt').first().waitFor({ state: 'attached' });
            assert.deepEqual(await frameSizes(), before, 'Unsaved changes must not reach frames');
            await panel.getByLabel('Set name', { exact: true }).fill(`${theme} specimen set`);
            await panel.getByRole('button', { name: 'Save as new set', exact: true }).click();
            await status('Set saved in library. Theme unchanged.');
            await page.reload();
            assert.equal(await heading.evaluate(el => getComputedStyle(el).fontSize), original, 'Library save must not publish');
            await page.getByRole('button', { name: 'Open theme designer', exact: true }).click();
            const library = await (await context.request.get(`${process.argv[2]}/modules/cssholmes/sets.php?theme=${theme}`)).json();
            const saved = library.library.sets.find(set => set.name === `${theme} specimen set`);
            assert.ok(saved);
            const originalPreview = await (await context.request.get(`${process.argv[2]}/modules/cssholmes/sets.php?theme=${theme}&action=preview&id=${saved.id}`)).json();
            await panel.getByLabel('Style sets', { exact: true }).selectOption(saved.id);
            await panel.getByRole('button', { name: 'Preview selected', exact: true }).click();
            await page.waitForFunction(() => getComputedStyle(document.querySelector('#xs-theme-cards_card-title')).fontSize === '31px');
            await panel.getByRole('button', { name: 'Save to theme', exact: true }).click();
            await status('Saved to theme.');
            await panel.getByRole('button', { name: 'Close', exact: true }).click();
            await frames();
            assert.deepEqual(await frameSizes(), ['31px', '31px', '31px'], 'Published CSS reaches all viewport widths');
            assert.equal(await page.locator('[data-xs-frames] iframe').evaluateAll(nodes => nodes.every(f => !f.contentDocument.querySelector('#cssholmes-designer'))), true);
            const visitor = await browser.newPage();
            await visitor.goto(url);
            assert.equal(await visitor.locator('#xs-theme-cards_card-title').evaluate(el => getComputedStyle(el).fontSize), '31px');
            assert.equal(await visitor.locator('#cssholmes-designer-config').count(), 0);
            await visitor.close();
            await page.getByRole('button', { name: 'Open theme designer', exact: true }).click();
            await panel.getByLabel('Style sets', { exact: true }).selectOption(saved.id);
            await panel.locator('[data-library-transfer] summary').click();
            const downloaded = page.waitForEvent('download');
            await panel.getByRole('button', { name: 'Export portable set', exact: true }).click();
            const stream = await (await downloaded).createReadStream(), chunks = [];
            for await (const chunk of stream) chunks.push(chunk);
            const json = Buffer.concat(chunks);
            const exported = JSON.parse(json);
            assert.equal(exported.format, 'xoops-theme-set');
            assert.equal(exported.sourceTheme, theme);
            assert.ok(exported.sourceRules.some(rule => rule.declarations['font-size'] === '31px'), 'Export preserves authored theme selectors');
            assert.deepEqual(exported.sourceRules, originalPreview.preview.rules, 'Export preserves every authored declaration');
            await panel.getByLabel('Import set JSON', { exact: true }).setInputFiles({ name: 'specimen-set.json', mimeType: 'application/json', buffer: json });
            await panel.getByRole('button', { name: 'Preview import', exact: true }).click();
            await panel.getByRole('button', { name: 'Save imported set', exact: true }).click();
            await status('Set saved in library. Theme unchanged.');
            await panel.locator('[data-library-original] summary').click();
            await panel.getByRole('button', { name: 'Reset theme to original', exact: true }).click();
            await status('Theme reset to original. Library sets kept.');
            await panel.getByRole('button', { name: 'Close', exact: true }).click();
            assert.equal(await heading.evaluate(el => getComputedStyle(el).fontSize), original);
            await page.locator('[data-xs-refresh]').click();
            await page.waitForFunction(() => [...document.querySelectorAll('[data-xs-frames] iframe')].every(f => f.contentDocument?.querySelector('#xs-theme-cards_card-title') && f.contentWindow.getComputedStyle(f.contentDocument.querySelector('#xs-theme-cards_card-title')).fontSize !== '31px'));
            const retained = await (await context.request.get(`${process.argv[2]}/modules/cssholmes/sets.php?theme=${theme}`)).json();
            assert.equal(retained.library.sets.filter(set => set.name === saved.name).length, 2);
            if (process.env.XSTYLES_SCREENSHOT_DIR) {
                fs.mkdirSync(process.env.XSTYLES_SCREENSHOT_DIR, { recursive: true });
                await page.locator('[data-xs-responsive]').screenshot({ path: path.join(process.env.XSTYLES_SCREENSHOT_DIR, `workflow-${engine}-${theme}.png`) });
            }
            const imported = retained.library.sets.find(set => set.name === saved.name && set.id !== saved.id);
            const importedPreview = await (await context.request.get(`${process.argv[2]}/modules/cssholmes/sets.php?theme=${theme}&action=preview&id=${imported.id}`)).json();
            assert.deepEqual(importedPreview.preview.rules, originalPreview.preview.rules, 'Import preserves every selector, mode, state and declaration');
            await page.getByRole('button', { name: 'Open theme designer', exact: true }).click();
            await panel.getByLabel('Style sets', { exact: true }).selectOption(imported.id);
            await panel.getByRole('button', { name: 'Preview selected', exact: true }).click();
            await page.waitForFunction(() => getComputedStyle(document.querySelector('#xs-theme-cards_card-title')).fontSize === '31px');
            assert.notDeepEqual(await frameSizes(), ['31px', '31px', '31px'], 'Imported preview must not republish');
            assert.deepEqual(errors, []);
            console.log(`${engine} ${theme}: select/edit/diagnostics, library reload, publish, 3 viewports, visitor CSS, exact export/import and reset passed.`);
            await context.close();
        }
    } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
